import minescript as m

'''
座標の向きメモ
Xが増える → 東 (East)
Xが減る → 西 (West)
Zが増える → 南 (South)
Zが減る → 北 (North)
'''

# -------------------------------------------------
# プレイヤーの現在位置をスタート地点とする
# -------------------------------------------------
px, py, pz = m.player_position()

# -------------------------------------------------
# 設定値
# -------------------------------------------------
BLOCK_TYPE = "minecraft:blue_concrete"  # 置き換えるブロック
LENGTH = 300                            # 作成する距離（ブロック数）
MAX_Y = 255                             # ワールド上限Y
MIN_Y = 0                               # ワールド下限Y

# -------------------------------------------------
# メイン処理
# 東方向（+X）に進みながら地面を検出して置き換える
# -------------------------------------------------
for i in range(LENGTH):
    x = int(px) + i    # X方向に進む（東）
    z = int(pz)        # Z座標は固定

    # 上から下にスキャンして
    # 最初に空気ではないブロック（＝地表）を探す
    for y in range(MAX_Y, MIN_Y - 1, -1):
        block = m.getblock(x, y, z)

        if block != "minecraft:air":
            # 見つけた地表ブロックを指定ブロックに置き換える
            m.execute(f"setblock {x} {y} {z} {BLOCK_TYPE}")
            break  # 次のX座標へ進む

# -------------------------------------------------
# 完了メッセージ
# -------------------------------------------------
m.echo(f"✅ {LENGTH}ブロックの地面置き換えコースを作成しました。")
