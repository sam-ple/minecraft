# ============================================================
# コマンド実行
# ============================================================


def run_command(command):
    """
    Minecraftのコマンドを実行する。
    """

    minescript.execute(command)


# ============================================================
# ☆ 中心を設置
# ============================================================


def generate_center(center_x, center_y, center_z):
    """
    ☆の位置に火のついていない焚き火を設置する。
    """

    minescript.echo(
        "Generating ☆ center..."
    )


    command = (
        "/setblock "
        + str(center_x)
        + " "
        + str(center_y)
        + " "
        + str(center_z)
        + " "
        + CAMPFIRE_BLOCK
        + "[lit=false]"
        + " replace"
    )


    run_command(command)


# ============================================================
# ● を設置
# ============================================================


def generate_dot_positions(center_x, center_y, center_z):
    """
    ●の配置を生成する。

    ●はY-1に設置する。
    """

    minescript.echo(
        "Generating ● positions..."
    )


    for offset_x, offset_z in DOT_POSITIONS:

        # ----------------------------------------------------
        # 実際の座標
        # ----------------------------------------------------

        block_x = center_x + offset_x
        block_y = center_y - 1
        block_z = center_z + offset_z


        # ----------------------------------------------------
        # ブロック設置
        # ----------------------------------------------------

        command = (
            "/setblock "
            + str(block_x)
            + " "
            + str(block_y)
            + " "
            + str(block_z)
            + " "
            + GROUND_BLOCK
            + " replace"
        )


        run_command(command)


# ============================================================
# 〇 を設置
# ============================================================


def generate_sign_positions(center_x, center_y, center_z):
    """
    〇の配置を生成する。

    〇はYに床置き看板を設置する。

    看板のrotationは固定値を使用する。
    """

    minescript.echo(
        "Generating 〇 positions..."
    )


    for offset_x, offset_z, rotation in SIGN_POSITIONS:

        # ----------------------------------------------------
        # 実際の座標
        # ----------------------------------------------------

        block_x = center_x + offset_x
        block_y = center_y
        block_z = center_z + offset_z


        # ----------------------------------------------------
        # 看板設置
        # ----------------------------------------------------

        command = (
            "/setblock "
            + str(block_x)
            + " "
            + str(block_y)
            + " "
            + str(block_z)
            + " "
            + SIGN_BLOCK
            + "[rotation="
            + str(rotation)
            + "] replace"
        )


        run_command(command)


        # ----------------------------------------------------
        # デバッグ表示
        # ----------------------------------------------------

        minescript.echo(
            "Sign : "
            + str(offset_x)
            + ", "
            + str(offset_z)
            + "  rotation="
            + str(rotation)
        )


# ============================================================
# メイン処理
# ============================================================


def main():

    # ========================================================
    # プレイヤー現在位置
    # ========================================================

    player_pos = minescript.player_position()


    # ========================================================
    # 実行地点
    #
    # 小数部分を切り捨ててブロック座標にする。
    # ========================================================

    center_x = math.floor(
        player_pos[0]
    )

    center_y = math.floor(
        player_pos[1]
    )

    center_z = math.floor(
        player_pos[2]
    )


    # ========================================================
    # 開始表示
    # ========================================================

    minescript.echo(
        "=========================================="
    )

    minescript.echo(
        "CIRCLE RACE GENERATOR"
    )

    minescript.echo(
        "Version : v0.0.04"
    )

    minescript.echo(
        "=========================================="
    )


    # ========================================================
    # 中心座標表示
    # ========================================================

    minescript.echo(
        "Center X : "
        + str(center_x)
    )

    minescript.echo(
        "Center Y : "
        + str(center_y)
    )

    minescript.echo(
        "Center Z : "
        + str(center_z)
    )


    # ========================================================
    # 配置数表示
    # ========================================================

    minescript.echo(
        "● count : "
        + str(
            len(DOT_POSITIONS)
        )
    )

    minescript.echo(
        "〇 count : "
        + str(
            len(SIGN_POSITIONS)
        )
    )


    # ========================================================
    # ☆生成
    # ========================================================

    generate_center(
        center_x,
        center_y,
        center_z
    )


    # ========================================================
    # ●生成
    # ========================================================

    generate_dot_positions(
        center_x,
        center_y,
        center_z
    )


    # ========================================================
    # 〇生成
    # ========================================================

    generate_sign_positions(
        center_x,
        center_y,
        center_z
    )


    # ========================================================
    # 完了
    # ========================================================

    minescript.echo(
        "=========================================="
    )

    minescript.echo(
        "Circle generation complete."
    )

    minescript.echo(
        "=========================================="
    )


# ============================================================
# 実行
# ============================================================


if __name__ == "__main__":
    main()
