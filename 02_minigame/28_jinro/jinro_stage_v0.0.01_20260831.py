# 【概要】
#
#   プレイヤーの現在位置を実行地点（☆）として、
#   円形の配置を生成する。
#
#
# ============================================================
#
# 【配置ルール】
#
#   ●
#     → 実行地点の Y - 1 にブロックを設置
#
#   〇
#     → 実行地点の Y に床置き看板を設置
#
#   ☆
#     → 実行地点
#     → 火のついていない焚き火を設置
#
#
# ============================================================
#
# 【v0.0.04変更点】
#
#   v0.0.03では、東西南北は正しいが、
#   斜め方向の看板が90度違う方向を向いていた。
#
#   そのため、斜め方向の看板のみrotationを
#   90度分補正した。
#
#   東西南北のrotationは変更していない。
#
#
# ============================================================


import math
import minescript


# ============================================================
# 設定
# ============================================================


# ------------------------------------------------------------
# ● の位置に設置するブロック
# ------------------------------------------------------------

GROUND_BLOCK = "minecraft:stone"


# ------------------------------------------------------------
# 〇 の位置に設置する看板
# ------------------------------------------------------------

SIGN_BLOCK = "minecraft:oak_sign"


# ------------------------------------------------------------
# ☆ の位置に設置する焚き火
# ------------------------------------------------------------

