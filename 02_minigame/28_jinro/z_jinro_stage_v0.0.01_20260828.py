#
# 【概要】
#
#   プレイヤーの現在位置を実行地点（☆）として、
#   図に示された円形配置を生成する。
#
#
# ============================================================
#
# 【● の円】
#
#   ● の位置：
#
#       Y - 1
#
#   にブロックを設置する。
#
#
# 【〇 の円】
#
#   〇 の位置：
#
#       Y
#
#   に看板を設置する。
#
#   看板の向きは円の中心（☆）を向く。
#
#
# 【☆】
#
#   実行地点。
#
#   現在位置に火のついていない焚き火を設置する。
#
#
# ============================================================
#
# 【重要】
#
#   今回は「円を数学的に計算」するのではなく、
#   ユーザーが提示した図の配置をそのまま座標パターンとして
#   定義している。
#
#   そのため、Minecraft上でも図と同じ形になる。
#
#
# ============================================================


import math
import minescript


# ============================================================
# 設定
# ============================================================


# ------------------------------------------------------------
# ● の下に設置するブロック
#
# ● の地点では、
#
#     Y - 1
#
# にこのブロックを設置する。
# ------------------------------------------------------------

GROUND_BLOCK = "minecraft:stone"


# ------------------------------------------------------------
# 〇 の地点に設置する看板
# ------------------------------------------------------------

SIGN_BLOCK = "minecraft:oak_sign"


# ------------------------------------------------------------
# ☆ の地点に設置する焚き火
#
# lit=false
#
# にすることで火を消した状態にする。
# ------------------------------------------------------------

CAMPFIRE_BLOCK = "minecraft:campfire"


# ============================================================
# ● の配置パターン
# ============================================================
#
# 図の●を、
#
#     X = 横方向
#     Z = 縦方向
#
# の相対座標として定義する。
#
#
# 中心 ☆ を
#
#     (0, 0)
#
# とする。
#
#
# 図：
#
#             ● ● ●
#
#         ● ●     ● ●
#       ●             ●
#     ●                 ●
#     ●                 ●
#   ●                       ●
#   ●         ☆             ●
#     ●                 ●
#     ●                 ●
#       ●             ●
#         ● ●     ● ●
#             ● ● ●
#
#
# ============================================================


DOT_POSITIONS = [

    # --------------------------------------------------------
    # 上側
    # --------------------------------------------------------

    (-1, -7),
    ( 0, -7),
    ( 1, -7),

    (-3, -5),
    (-2, -5),
    ( 2, -5),
    ( 3, -5),

    (-4, -4),
    ( 4, -4),

    (-5, -3),
    ( 5, -3),

    (-5, -2),
    ( 5, -2),

    (-6, -1),
    ( 6, -1),

    (-6,  0),
    ( 6,  0),

    (-6,  1),
    ( 6,  1),

    (-5,  2),
    ( 5,  2),

    (-5,  3),
    ( 5,  3),

    (-4,  4),
    ( 4,  4),

    (-3,  5),
    (-2,  5),
    ( 2,  5),
    ( 3,  5),

    (-1,  6),
    ( 0,  6),
    ( 1,  6),
]


# ============================================================
# 〇 の配置パターン
# ============================================================
#
# 図の〇を、
#
#     X = 横方向
#     Z = 縦方向
#
# の相対座標として定義する。
#
#
# 中心 ☆：
#
#     (0, 0)
#
#
# ============================================================


SIGN_POSITIONS = [

    # --------------------------------------------------------
    # 最上部
    # --------------------------------------------------------

    (0, -6),

    # --------------------------------------------------------
    # 上斜め
    # --------------------------------------------------------

    (-3, -5),
    ( 3, -5),

    # --------------------------------------------------------
    # 上側
    # --------------------------------------------------------

    (-5, -3),
    ( 5, -3),

    # --------------------------------------------------------
    # 左右
    # --------------------------------------------------------

    (-6, 0),
    ( 6, 0),

    # --------------------------------------------------------
    # 下側
    # --------------------------------------------------------

    (-5, 3),
    ( 5, 3),

    # --------------------------------------------------------
    # 下斜め
    # --------------------------------------------------------

    (-3, 5),
    ( 3, 5),

    # --------------------------------------------------------
    # 最下部
    # --------------------------------------------------------

    (0, 6),
]


# ============================================================
# コマンド実行
# ============================================================

def run_command(command):
    """
    Minecraftのコマンドを実行する。
    """

    minescript.execute(command)


# ============================================================
# 看板の向きを計算
# ============================================================

def get_sign_rotation(offset_x, offset_z):
    """
    円周上にある看板を、
    円の中心方向へ向けるためのrotation値を計算する。

    offset_x / offset_z は、

        中心 → 看板

    の相対座標。

    その逆方向、

        看板 → 中心

    を向くようにする。
    """

    # --------------------------------------------------------
    # 看板から中心へ向かう方向
    # --------------------------------------------------------

    target_x = -offset_x
    target_z = -offset_z


    # --------------------------------------------------------
    # Minecraftの水平角度を計算
    #
    # atan2(X, Z) とすることで、
    # MinecraftのZ方向を基準にした角度になる。
    # --------------------------------------------------------

    angle = math.degrees(
        math.atan2(
            target_x,
            target_z
        )
    )


    # --------------------------------------------------------
    # 0～360°に変換
    # --------------------------------------------------------

    angle = angle % 360


    # --------------------------------------------------------
    # Minecraftの看板rotationは16方向
    #
    # 360 / 16 = 22.5°
    # --------------------------------------------------------

    rotation = round(
        angle / 22.5
    ) % 16


    return rotation


# ============================================================
# メイン
# ============================================================

def main():

    # ========================================================
    # 実行地点取得
    # ========================================================

    player_pos = minescript.player_position()


    # --------------------------------------------------------
    # プレイヤーの現在座標
    # --------------------------------------------------------

    center_x = math.floor(player_pos[0])
    center_y = math.floor(player_pos[1])
    center_z = math.floor(player_pos[2])


    # ========================================================
    # 開始表示
    # ========================================================

    minescript.echo(
        "=========================================="
    )

    minescript.echo(
        "CIRCLE RACE GENERATOR"
    )

    minescript.echo(
        "=========================================="
    )

    minescript.echo(
        "Center : "
        + str(center_x)
        + " "
        + str(center_y)
        + " "
        + str(center_z)
    )

    minescript.echo(
        "DOT count  : "
        + str(len(DOT_POSITIONS))
    )

    minescript.echo(
        "SIGN count : "
        + str(len(SIGN_POSITIONS))
    )


    # ========================================================
    # ☆ 中心
    # ========================================================
    #
    # 現在位置に火のついていない焚き火を設置。
    #
    # ========================================================

    center_command = (
        "/setblock "
        + str(center_x)
        + " "
        + str(center_y)
        + " "
        + str(center_z)
        + " "
        + CAMPFIRE_BLOCK
        + "[lit=false]"
        + " replace"
    )

    run_command(center_command)


    # ========================================================
    # ● の生成
    # ========================================================
    #
    # ● は Y-1 にブロックを設置。
    #
    # ========================================================

    minescript.echo(
        "Generating ● positions..."
    )


    for offset_x, offset_z in DOT_POSITIONS:

        # ----------------------------------------------------
        # 実際のMinecraft座標
        # ----------------------------------------------------

        block_x = center_x + offset_x
        block_y = center_y - 1
        block_z = center_z + offset_z


        # ----------------------------------------------------
        # ブロック設置
        # ----------------------------------------------------

        command = (
            "/setblock "
            + str(block_x)
            + " "
            + str(block_y)
            + " "
            + str(block_z)
            + " "
            + GROUND_BLOCK
            + " replace"
        )

        run_command(command)


    # ========================================================
    # 〇 の生成
    # ========================================================
    #
    # 〇 は Y に看板を設置。
    #
    # 看板は中心方向を向く。
    #
    # ========================================================

    minescript.echo(
        "Generating 〇 positions..."
    )


    for offset_x, offset_z in SIGN_POSITIONS:

        # ----------------------------------------------------
        # 実際のMinecraft座標
        # ----------------------------------------------------

        block_x = center_x + offset_x
        block_y = center_y
        block_z = center_z + offset_z


        # ----------------------------------------------------
        # 中心方向を向くrotationを計算
        # ----------------------------------------------------

        rotation = get_sign_rotation(
            offset_x,
            offset_z
        )


        # ----------------------------------------------------
        # 看板設置
        # ----------------------------------------------------

        command = (
            "/setblock "
            + str(block_x)
            + " "
            + str(block_y)
            + " "
            + str(block_z)
            + " "
            + SIGN_BLOCK
            + "[rotation="
            + str(rotation)
            + "] replace"
        )

        run_command(command)


    # ========================================================
    # 完了
    # ========================================================

    minescript.echo(
        "=========================================="
    )

    minescript.echo(
        "Circle generation complete."
    )

    minescript.echo(
        "=========================================="
    )


# ============================================================
# 実行
# ============================================================

if __name__ == "__main__":
    main()