# 【概要】
#
#   プレイヤーの現在位置を実行地点（☆）として、
#   図に示された円形配置を生成する。
#
#
# ============================================================
#
# 【配置ルール】
#
#   ●
#     → 実行地点の Y - 1 にブロックを設置
#
#   〇
#     → 実行地点の Y に床置き看板を設置
#
#   ☆
#     → 実行地点
#     → 火のついていない焚き火を設置
#
#
# ============================================================
#
# 【看板】
#
#   〇の位置に設置する看板は、
#   円の中心にある☆の方向を向く。
#
#   床置き看板の
#
#       rotation=0～15
#
#   を使用して16方向に角度を調整する。
#
#
# ============================================================
#
# 【座標】
#
#   実行したプレイヤーの現在位置を
#
#       X = 0
#       Y = 0
#       Z = 0
#
#   とした相対座標で配置パターンを管理する。
#
#   実際のMinecraft座標は、
#   実行地点の座標を加算して求める。
#
#
# ============================================================
#
# 【重要】
#
#   円を数学的に生成するのではなく、
#   ユーザーが提示した図の●・〇の配置を
#   座標パターンとしてそのまま使用する。
#
#
