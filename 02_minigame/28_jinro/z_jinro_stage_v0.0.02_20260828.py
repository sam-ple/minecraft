# ============================================================
# コマンド実行関数
# ============================================================


def run_command(command):
    """
    Minecraftのコマンドを実行する。

    コマンド実行処理を1か所にまとめておくことで、
    今後コマンドを変更するときにも管理しやすくする。
    """

    minescript.execute(command)


# ============================================================
# 看板rotation計算
# ============================================================


def get_sign_rotation(offset_x, offset_z):
    """
    〇地点の看板を中心方向へ向けるための
    rotation値を計算する。

    ------------------------------------------------------------
    入力
    ------------------------------------------------------------

    offset_x
        中心から見た看板のX方向の距離。

    offset_z
        中心から見た看板のZ方向の距離。

    ------------------------------------------------------------
    出力
    ------------------------------------------------------------

    0～15

    床置き看板のrotation値。

    ------------------------------------------------------------

    例：

        看板
          ↓
        中心

    の場合は中心方向を向くrotationを返す。
    """


    # ========================================================
    # 看板 → 中心
    #
    # offset_x / offset_z は
    #
    #     中心 → 看板
    #
    # なので、符号を反転すると
    #
    #     看板 → 中心
    #
    # になる。
    # ========================================================

    target_x = -offset_x
    target_z = -offset_z


    # ========================================================
    # 角度計算
    #
    # atan2(X, Z)
    #
    # Minecraftの水平面上の方向を角度へ変換する。
    # ========================================================

    angle = math.degrees(
        math.atan2(
            target_x,
            target_z
        )
    )


    # ========================================================
    # 0～360度へ変換
    # ========================================================

    angle = angle % 360


    # ========================================================
    # 16方向へ変換
    #
    # 360 / 16
    #
    # = 22.5度
    #
    # 22.5度単位で最も近い方向へ丸める。
    # ========================================================

    rotation = round(
        angle / 22.5
    ) % 16


    return rotation


# ============================================================
# ● を設置
# ============================================================


def generate_dot_positions(center_x, center_y, center_z):
    """
    ● の配置を生成する。

    ● は、

        Y - 1

    にGROUND_BLOCKを設置する。
    """


    minescript.echo(
        "Generating ● positions..."
    )


    # ========================================================
    # ●を1つずつ処理
    # ========================================================

    for offset_x, offset_z in DOT_POSITIONS:


        # ----------------------------------------------------
        # 実際のX座標
        # ----------------------------------------------------

        block_x = center_x + offset_x


        # ----------------------------------------------------
        # ●はY-1
        # ----------------------------------------------------

        block_y = center_y - 1


        # ----------------------------------------------------
        # 実際のZ座標
        # ----------------------------------------------------

        block_z = center_z + offset_z


        # ====================================================
        # ブロック設置
        # ====================================================

        command = (
            "/setblock "
            + str(block_x)
            + " "
            + str(block_y)
            + " "
            + str(block_z)
            + " "
            + GROUND_BLOCK
            + " replace"
        )


        run_command(command)


# ============================================================
# 〇 を設置
# ============================================================


def generate_sign_positions(center_x, center_y, center_z):
    """
    〇 の配置を生成する。

    〇は、

        Y

    に床置き看板を設置する。

    看板は中心方向を向く。
    """


    minescript.echo(
        "Generating 〇 positions..."
    )


    # ========================================================
    # 〇を1つずつ処理
    # ========================================================

    for offset_x, offset_z in SIGN_POSITIONS:


        # ----------------------------------------------------
        # 実際のX座標
        # ----------------------------------------------------

        block_x = center_x + offset_x


        # ----------------------------------------------------
        # 〇はY
        # ----------------------------------------------------

        block_y = center_y


        # ----------------------------------------------------
        # 実際のZ座標
        # ----------------------------------------------------

        block_z = center_z + offset_z


        # ====================================================
        # 中心方向を向くrotationを計算
        # ====================================================

        rotation = get_sign_rotation(
            offset_x,
            offset_z
        )


        # ====================================================
        # 看板設置
        #
        # 例：
        #
        # /setblock X Y Z minecraft:oak_sign[rotation=4]
        #
        # ====================================================

        command = (
            "/setblock "
            + str(block_x)
            + " "
            + str(block_y)
            + " "
            + str(block_z)
            + " "
            + SIGN_BLOCK
            + "[rotation="
            + str(rotation)
            + "] replace"
        )


        run_command(command)


# ============================================================
# ☆ 中心を設置
# ============================================================


def generate_center(center_x, center_y, center_z):
    """
    ☆の位置に火のついていない焚き火を設置する。
    """


    minescript.echo(
        "Generating ☆ center..."
    )


    # ========================================================
    # 焚き火設置
    #
    # lit=false
    #
    # により火のついていない焚き火にする。
    # ========================================================

    command = (
        "/setblock "
        + str(center_x)
        + " "
        + str(center_y)
        + " "
        + str(center_z)
        + " "
        + CAMPFIRE_BLOCK
        + "[lit=false]"
        + " replace"
    )


    run_command(command)


# ============================================================
# メイン処理
# ============================================================


def main():

    # ========================================================
    # プレイヤー現在位置取得
    # ========================================================

    player_pos = minescript.player_position()


    # ========================================================
    # 実行地点の座標
    #
    # 小数を切り捨ててブロック座標にする。
    # ========================================================

    center_x = math.floor(
        player_pos[0]
    )

    center_y = math.floor(
        player_pos[1]
    )

    center_z = math.floor(
        player_pos[2]
    )


    # ========================================================
    # 開始表示
    # ========================================================

    minescript.echo(
        "=========================================="
    )

    minescript.echo(
        "CIRCLE RACE GENERATOR"
    )

    minescript.echo(
        "Version : v0.0.02"
    )

    minescript.echo(
        "=========================================="
    )


    # ========================================================
    # 中心座標表示
    # ========================================================

    minescript.echo(
        "Center X : "
        + str(center_x)
    )

    minescript.echo(
        "Center Y : "
        + str(center_y)
    )

    minescript.echo(
        "Center Z : "
        + str(center_z)
    )


    # ========================================================
    # 配置数表示
    # ========================================================

    minescript.echo(
        "● count : "
        + str(
            len(DOT_POSITIONS)
        )
    )

    minescript.echo(
        "〇 count : "
        + str(
            len(SIGN_POSITIONS)
        )
    )


    # ========================================================
    # ☆を設置
    # ========================================================

    generate_center(
        center_x,
        center_y,
        center_z
    )


    # ========================================================
    # ●を設置
    #
    # Y-1
    # ========================================================

    generate_dot_positions(
        center_x,
        center_y,
        center_z
    )


    # ========================================================
    # 〇を設置
    #
    # Y
    #
    # 看板は中心方向を向く。
    # ========================================================

    generate_sign_positions(
        center_x,
        center_y,
        center_z
    )


    # ========================================================
    # 完了表示
    # ========================================================

    minescript.echo(
        "=========================================="
    )

    minescript.echo(
        "Circle generation complete."
    )

    minescript.echo(
        "=========================================="
    )


# ============================================================
# 実行
# ============================================================


if __name__ == "__main__":
    main()