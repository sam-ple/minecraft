# ============================================================
# CIRCLE RACE GENERATOR
# Version : v0.0.05
# Date    : 2026-09-01
#
# Minecraft Java Edition + Minescript
#
# ============================================================
#
# 【概要】
#
#   プレイヤーの現在位置を実行地点（☆）として、
#   円形の配置を生成する。
#
#
# ============================================================
#
# 【配置ルール】
#
#   ●
#     → 実行地点の Y - 1 にブロックを設置
#
#   〇
#     → 実行地点の Y に床置き看板を設置
#
#   ☆
#     → 実行地点
#     → 火のついていない焚き火を設置
#
#   START BLOCK
#     → ☆の東側（X + 1）
#     → 石ブロックを設置
#
#
# ============================================================
#
# 【スタートシステム】
#
#   ☆の近くにある石ブロックをSkriptからクリックすると、
#
#       石ブロック消滅
#            ↓
#       焚き火点火
#            ↓
#       CIRCLE RACE START
#
#   ゲーム終了時にはSkript側で、
#
#       焚き火消火
#            ↓
#       石ブロック復活
#
#   とする。
#
#
# ============================================================
#
# 【看板】
#
#   〇の位置に設置する床置き看板。
#
#   看板のrotationは固定値を使用する。
#
#
# ============================================================


import math
import minescript


# ============================================================
# 設定
# ============================================================


# ------------------------------------------------------------
# ● の位置に設置するブロック
# ------------------------------------------------------------

GROUND_BLOCK = "minecraft:stone"


# ------------------------------------------------------------
# 〇 の位置に設置する看板
# ------------------------------------------------------------

SIGN_BLOCK = "minecraft:oak_sign"


# ------------------------------------------------------------
# ☆ の位置に設置する焚き火
# ------------------------------------------------------------

CAMPFIRE_BLOCK = "minecraft:campfire"


# ------------------------------------------------------------
# スタート用石ブロック
#
# ☆の東側（X + 1）に設置する。
# ------------------------------------------------------------

START_BLOCK = "minecraft:stone"


# ============================================================
# ● の配置パターン
# ============================================================
#
# 中心の☆を
#
#       (0, 0)
#
# とした相対座標。
#
#
#             ● ● ●
#
#         ● ●     ● ●
#
#       ●             ●
#
#     ●                 ●
#
#     ●                 ●
#
#   ●                       ●
#
#   ●                       ●
#
#   ●         ☆             ●
#
#   ●                       ●
#
#   ●                       ●
#
#     ●                 ●
#
#     ●                 ●
#
#       ●             ●
#
#         ● ●     ● ●
#
#             ● ● ●
#
#
# ============================================================


DOT_POSITIONS = [

    # --------------------------------------------------------
    # 上段
    # --------------------------------------------------------

    (-1, -7),
    ( 0, -7),
    ( 1, -7),

    # --------------------------------------------------------
    # 上部斜め
    # --------------------------------------------------------

    (-3, -5),
    (-2, -5),
    ( 2, -5),
    ( 3, -5),

    # --------------------------------------------------------
    # 上側
    # --------------------------------------------------------

    (-4, -4),
    ( 4, -4),

    (-5, -3),
    ( 5, -3),

    (-5, -2),
    ( 5, -2),

    # --------------------------------------------------------
    # 左右上
    # --------------------------------------------------------

    (-6, -1),
    ( 6, -1),

    # --------------------------------------------------------
    # 左右中央
    # --------------------------------------------------------

    (-6, 0),
    ( 6, 0),

    # --------------------------------------------------------
    # 左右下
    # --------------------------------------------------------

    (-6, 1),
    ( 6, 1),

    (-5, 2),
    ( 5, 2),

    (-5, 3),
    ( 5, 3),

    # --------------------------------------------------------
    # 下側
    # --------------------------------------------------------

    (-4, 4),
    ( 4, 4),

    # --------------------------------------------------------
    # 下部斜め
    # --------------------------------------------------------

    (-3, 5),
    (-2, 5),
    ( 2, 5),
    ( 3, 5),

    # --------------------------------------------------------
    # 下段
    # --------------------------------------------------------

    (-1, 6),
    ( 0, 6),
    ( 1, 6),
]


# ============================================================
# 〇 の配置パターン
# ============================================================
#
# 各要素：
#
#     (offset_x, offset_z, rotation)
#
#
# rotationは固定値。
#
# ============================================================


SIGN_POSITIONS = [

    # --------------------------------------------------------
    # 北
    # --------------------------------------------------------

    ( 0, -6,  0),

    # --------------------------------------------------------
    # 北西
    # --------------------------------------------------------

    (-3, -5,  6),

    # --------------------------------------------------------
    # 北東
    # --------------------------------------------------------

    ( 3, -5,  2),

    # --------------------------------------------------------
    # 西北
    # --------------------------------------------------------

    (-5, -3,  6),

    # --------------------------------------------------------
    # 東北
    # --------------------------------------------------------

    ( 5, -3,  2),

    # --------------------------------------------------------
    # 西
    # --------------------------------------------------------

    (-6, 0,  4),

    # --------------------------------------------------------
    # 東
    # --------------------------------------------------------

    ( 6, 0, 12),

    # --------------------------------------------------------
    # 西南
    # --------------------------------------------------------

    (-5, 3, 10),

    # --------------------------------------------------------
    # 東南
    # --------------------------------------------------------

    ( 5, 3, 14),

    # --------------------------------------------------------
    # 南西
    # --------------------------------------------------------

    (-3, 5, 10),

    # --------------------------------------------------------
    # 南東
    # --------------------------------------------------------

    ( 3, 5, 14),

    # --------------------------------------------------------
    # 南
    # --------------------------------------------------------

    ( 0, 6,  8),
]


# ============================================================
# コマンド実行
# ============================================================


def run_command(command):
    """
    Minecraftのコマンドを実行する。
    """

    minescript.execute(command)


# ============================================================
# ☆ 中心を設置
# ============================================================


def generate_center(center_x, center_y, center_z):
    """
    ☆の位置に火のついていない焚き火を設置する。
    """

    minescript.echo(
        "Generating ☆ center..."
    )


    # --------------------------------------------------------
    # 火のついていない焚き火
    # --------------------------------------------------------

    command = (
        "/setblock "
        + str(center_x)
        + " "
        + str(center_y)
        + " "
        + str(center_z)
        + " "
        + CAMPFIRE_BLOCK
        + "[lit=false]"
        + " replace"
    )


    run_command(command)


# ============================================================
# START BLOCK
# ============================================================


def generate_start_block(center_x, center_y, center_z):
    """
    スタート用石ブロックを設置する。

    位置：
        ☆の東側
        X + 1
        Y
        Z
    """

    minescript.echo(
        "Generating START block..."
    )


    # --------------------------------------------------------
    # スタート用石の座標
    # --------------------------------------------------------

    block_x = center_x + 1
    block_y = center_y
    block_z = center_z


    # --------------------------------------------------------
    # 石を設置
    # --------------------------------------------------------

    command = (
        "/setblock "
        + str(block_x)
        + " "
        + str(block_y)
        + " "
        + str(block_z)
        + " "
        + START_BLOCK
        + " replace"
    )


    run_command(command)


    # --------------------------------------------------------
    # デバッグ表示
    # --------------------------------------------------------

    minescript.echo(
        "START block : "
        + str(block_x)
        + " "
        + str(block_y)
        + " "
        + str(block_z)
    )


# ============================================================
# ● を設置
# ============================================================


def generate_dot_positions(center_x, center_y, center_z):
    """
    ●の配置を生成する。

    ●はY-1に設置する。
    """

    minescript.echo(
        "Generating ● positions..."
    )


    for offset_x, offset_z in DOT_POSITIONS:

        # ----------------------------------------------------
        # 実際の座標
        # ----------------------------------------------------

        block_x = center_x + offset_x
        block_y = center_y - 1
        block_z = center_z + offset_z


        # ----------------------------------------------------
        # ブロック設置
        # ----------------------------------------------------

        command = (
            "/setblock "
            + str(block_x)
            + " "
            + str(block_y)
            + " "
            + str(block_z)
            + " "
            + GROUND_BLOCK
            + " replace"
        )


        run_command(command)


# ============================================================
# 〇 を設置
# ============================================================


def generate_sign_positions(center_x, center_y, center_z):
    """
    〇の配置を生成する。

    〇はYに床置き看板を設置する。

    看板のrotationは固定値を使用する。
    """

    minescript.echo(
        "Generating 〇 positions..."
    )


    for offset_x, offset_z, rotation in SIGN_POSITIONS:

        # ----------------------------------------------------
        # 実際の座標
        # ----------------------------------------------------

        block_x = center_x + offset_x
        block_y = center_y
        block_z = center_z + offset_z


        # ----------------------------------------------------
        # 看板設置
        # ----------------------------------------------------

        command = (
            "/setblock "
            + str(block_x)
            + " "
            + str(block_y)
            + " "
            + str(block_z)
            + " "
            + SIGN_BLOCK
            + "[rotation="
            + str(rotation)
            + "] replace"
        )


        run_command(command)


        # ----------------------------------------------------
        # デバッグ表示
        # ----------------------------------------------------

        minescript.echo(
            "Sign : "
            + str(offset_x)
            + ", "
            + str(offset_z)
            + "  rotation="
            + str(rotation)
        )


# ============================================================
# メイン処理
# ============================================================


def main():

    # ========================================================
    # プレイヤー現在位置
    # ========================================================

    player_pos = minescript.player_position()


    # ========================================================
    # 実行地点
    #
    # 小数部分を切り捨ててブロック座標にする。
    # ========================================================

    center_x = math.floor(
        player_pos[0]
    )

    center_y = math.floor(
        player_pos[1]
    )

    center_z = math.floor(
        player_pos[2]
    )


    # ========================================================
    # 開始表示
    # ========================================================

    minescript.echo(
        "=========================================="
    )

    minescript.echo(
        "CIRCLE RACE GENERATOR"
    )

    minescript.echo(
        "Version : v0.0.05"
    )

    minescript.echo(
        "=========================================="
    )


    # ========================================================
    # 中心座標
    # ========================================================

    minescript.echo(
        "Center X : "
        + str(center_x)
    )

    minescript.echo(
        "Center Y : "
        + str(center_y)
    )

    minescript.echo(
        "Center Z : "
        + str(center_z)
    )


    # ========================================================
    # 配置数
    # ========================================================

    minescript.echo(
        "● count : "
        + str(
            len(DOT_POSITIONS)
        )
    )

    minescript.echo(
        "〇 count : "
        + str(
            len(SIGN_POSITIONS)
        )
    )


    # ========================================================
    # ☆生成
    # ========================================================

    generate_center(
        center_x,
        center_y,
        center_z
    )


    # ========================================================
    # スタート用石生成
    #
    # ☆の東側
    # ========================================================

    generate_start_block(
        center_x,
        center_y,
        center_z
    )


    # ========================================================
    # ●生成
    #
    # Y-1
    # ========================================================

    generate_dot_positions(
        center_x,
        center_y,
        center_z
    )


    # ========================================================
    # 〇生成
    #
    # Y
    #
    # 看板は中心方向を向く。
    # ========================================================

    generate_sign_positions(
        center_x,
        center_y,
        center_z
    )


    # ========================================================
    # 完了
    # ========================================================

    minescript.echo(
        "=========================================="
    )

    minescript.echo(
        "Circle generation complete."
    )

    minescript.echo(
        "=========================================="
    )


# ============================================================
# 実行
# ============================================================


if __name__ == "__main__":
    main()