# === 描画関数 ===
def draw_art(start_x, start_y, start_z, art, offset_x=8, offset_z=10, sound="minecraft:block.amethyst_block.chime", delay=0):
    for dy, row in enumerate(art):
        for dx, val in enumerate(row):
            block = block_map.get(val)
            if block:
                bx = start_x + dx - offset_x
                by = start_y
                bz = start_z + dy - offset_z
                execute(f"/setblock {bx} {by} {bz} minecraft:{block}")
                execute(f"playsound {sound} master @p ~ ~ ~ 1 1")
                time.sleep(delay)

# === 描画ループ ===
for i, frame in enumerate(sheep_frames):
    draw_art(x, y + i, z, frame)
    time.sleep(0.1)

